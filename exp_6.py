# ==========================================
# EXPERIMENT: ROLE-BASED AND NEGATIVE PROMPTING
# ==========================================

# STEP 1: Install the Gemini SDK
# %pip install -q -U google-genai

# STEP 2: Import libraries
import time
from getpass import getpass
from google import genai
from google.genai import errors

# STEP 3: Configure Gemini API
API_KEY = getpass("Enter your Gemini API key: ")

client = genai.Client(api_key=API_KEY)

# Use the model specified in your API error message
MODEL = "gemini-3.8-flash"

# ==========================================
# STEP 4: Define the three prompts
# ==========================================

# Prompt 1: Baseline
baseline_prompt = """
Explain the importance of exercise.
"""

# Prompt 2: Role-based only
role_prompt = """
You are a motivational fitness coach.
Explain the importance of exercise.
"""

# Prompt 3: Role + negative prompting
negative_prompt = """
You are a motivational fitness coach.
Do not use any medical jargon.
Do not mention weight loss.

Explain the importance of exercise.
"""

# ==========================================
# STEP 5: Generate response with retry
# ==========================================

def generate_with_retry(prompt):
    for attempt in range(4):
        try:
            response = client.models.generate_content(
                model=MODEL,
                contents=prompt,
                config={
                    "temperature": 0.7
                }
            )
            return response

        except errors.ServerError:
            if attempt == 3:
                raise

            wait_seconds = 2 ** (attempt + 1)
            print(
                f"Temporary server error. Retrying in "
                f"{wait_seconds} seconds..."
            )
            time.sleep(wait_seconds)

# ==========================================
# STEP 6: Generate all responses
# ==========================================

try:
    baseline_response = generate_with_retry(baseline_prompt)
    role_response = generate_with_retry(role_prompt)
    negative_response = generate_with_retry(negative_prompt)

    # ==========================================
    # STEP 7: Display responses
    # ==========================================

    print("\n========== BASELINE ==========")
    print(baseline_response.text or "No text returned.")

    print("\n========== ROLE-BASED (FITNESS COACH) ==========")
    print(role_response.text or "No text returned.")

    print("\n========== ROLE + NEGATIVE PROMPTING ==========")
    print(negative_response.text or "No text returned.")

    # ==========================================
    # STEP 8: Analyse tone and vocabulary
    # ==========================================

    print("\n========== OUTPUT ANALYSIS ==========")

    print("""
    1. TONE:
       Baseline: Expected to be neutral and informative.
       Role-based: Expected to be motivational and encouraging.
       Role + negative: Expected to remain motivational.

    2. VOCABULARY:
       Compare general explanatory words with energetic,
       friendly, and encouraging expressions.

    3. CONSTRAINT ADHERENCE:
       Check whether the final response avoids medical jargon
       and does not mention weight loss.
    """)

    # ==========================================
    # STEP 9: Basic constraint verification
    # ==========================================

    final_text = (negative_response.text or "").lower()

    medical_terms = [
        "cardiovascular",
        "hypertension",
        "metabolism",
        "aerobic capacity"
    ]

    weight_loss_terms = [
        "weight loss",
        "lose weight",
        "losing weight",
        "burn fat"
    ]

    medical_found = [
        term for term in medical_terms
        if term in final_text
    ]

    weight_found = [
        term for term in weight_loss_terms
        if term in final_text
    ]

    print("\n========== CONSTRAINT CHECK ==========")

    if medical_found:
        print("Review possible medical jargon:", medical_found)
    else:
        print("No listed medical terms detected.")

    if weight_found:
        print("Weight-loss phrases detected:", weight_found)
    else:
        print("No listed weight-loss phrases detected.")

    print("""
    Note: This keyword check is not a complete semantic evaluation.
    Manually review the final response to confirm both constraints.
    """)

except errors.ClientError as e:
    print("\nGemini API request failed.")
    print("Check your API key, model availability, and API access.")
    print("Details:", e)

except Exception as e:
    print("\nAn unexpected error occurred:", e)

